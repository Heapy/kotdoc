// Exact declaration-field projection of Text.Pandoc.Error.
package io.heapy.kotdoc.errors

internal fun errorShape(e: PandocError): Pair<String, List<Any>> = when(e) {
    is PandocError.PandocIOError -> "PandocIOError" to listOf(e.context, e.error)
    is PandocError.PandocHttpError -> "PandocHttpError" to listOf(e.url, e.detail)
    is PandocError.PandocShouldNeverHappenError -> "PandocShouldNeverHappenError" to listOf(e.detail)
    is PandocError.PandocSomeError -> "PandocSomeError" to listOf(e.detail)
    is PandocError.PandocParseError -> "PandocParseError" to listOf(e.detail)
    is PandocError.PandocMakePDFError -> "PandocMakePDFError" to listOf(e.detail)
    is PandocError.PandocOptionError -> "PandocOptionError" to listOf(e.detail)
    is PandocError.PandocSyntaxMapError -> "PandocSyntaxMapError" to listOf(e.detail)
    PandocError.PandocFailOnWarningError -> "PandocFailOnWarningError" to listOf()
    is PandocError.PandocPDFProgramNotFoundError -> "PandocPDFProgramNotFoundError" to listOf(e.program)
    is PandocError.PandocPDFError -> "PandocPDFError" to listOf(e.detail)
    is PandocError.PandocXMLError -> "PandocXMLError" to listOf(e.file, e.detail)
    is PandocError.PandocFilterError -> "PandocFilterError" to listOf(e.filter, e.detail)
    is PandocError.PandocLuaError -> "PandocLuaError" to listOf(e.detail)
    PandocError.PandocNoScriptingEngine -> "PandocNoScriptingEngine" to listOf()
    is PandocError.PandocCouldNotFindDataFileError -> "PandocCouldNotFindDataFileError" to listOf(e.file)
    is PandocError.PandocCouldNotFindMetadataFileError -> "PandocCouldNotFindMetadataFileError" to listOf(e.file)
    is PandocError.PandocResourceNotFound -> "PandocResourceNotFound" to listOf(e.file)
    is PandocError.PandocTemplateError -> "PandocTemplateError" to listOf(e.template)
    is PandocError.PandocNoTemplateError -> "PandocNoTemplateError" to listOf(e.file)
    is PandocError.PandocAppError -> "PandocAppError" to listOf(e.detail)
    is PandocError.PandocEpubSubdirectoryError -> "PandocEpubSubdirectoryError" to listOf(e.directory)
    is PandocError.PandocMacroLoop -> "PandocMacroLoop" to listOf(e.macro)
    is PandocError.PandocUTF8DecodingError -> "PandocUTF8DecodingError" to listOf(e.file, e.offset, e.byte)
    is PandocError.PandocIpynbDecodingError -> "PandocIpynbDecodingError" to listOf(e.detail)
    is PandocError.PandocUnsupportedCharsetError -> "PandocUnsupportedCharsetError" to listOf(e.charset)
    is PandocError.PandocFormatError -> "PandocFormatError" to listOf(e.format, e.detail)
    is PandocError.PandocUnknownReaderError -> "PandocUnknownReaderError" to listOf(e.reader)
    is PandocError.PandocUnknownWriterError -> "PandocUnknownWriterError" to listOf(e.writer)
    is PandocError.PandocUnsupportedExtensionError -> "PandocUnsupportedExtensionError" to listOf(e.extension, e.format)
    is PandocError.PandocCiteprocError -> "PandocCiteprocError" to listOf(e.error)
    is PandocError.PandocBibliographyError -> "PandocBibliographyError" to listOf(e.file, e.detail)
    is PandocError.PandocInputNotTextError -> "PandocInputNotTextError" to listOf(e.file)
}
