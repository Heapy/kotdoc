package io.heapy.kotdoc.options

import io.heapy.kotdoc.highlighting.SyntaxMap
import io.heapy.kotdoc.highlighting.Syntaxes
import io.heapy.kotdoc.highlighting.syntaxMap as snapshotSyntaxMap
import io.heapy.kotdoc.structure.PathTemplate
import io.heapy.kotdoc.templates.Context
import io.heapy.kotdoc.templates.Template
import java.util.Collections

/** Complete library writer options, preserving compiled templates and contexts. */
class WriterOptions(
    val template: Template<String>? = null,
    val variables: Context<String> = Context(),
    val tabStop: Long = 4,
    val tableOfContents: Boolean = false,
    val listOfFigures: Boolean = false,
    val listOfTables: Boolean = false,
    val incremental: Boolean = false,
    val mathMethod: MathMethod = MathMethod.MathML,
    val numberSections: Boolean = false,
    numberOffset: List<Long> = listOf(0,0,0,0,0,0),
    val sectionDivs: Boolean = false,
    override val extensions: Extensions = Extensions.Empty,
    val referenceLinks: Boolean = false,
    val dpi: Long = 96,
    val wrapText: WrapOption = WrapOption.WrapAuto,
    val columns: Long = 72,
    val emailObfuscation: ObfuscationMethod = ObfuscationMethod.NoObfuscation,
    val identifierPrefix: String = "",
    val citeMethod: CiteMethod = CiteMethod.Citeproc,
    val htmlQTags: Boolean = false,
    val slideLevel: Long? = null,
    val topLevelDivision: TopLevelDivision = TopLevelDivision.TopLevelDefault,
    val highlightMethod: HighlightMethod = HighlightMethod.DefaultHighlighting,
    val setextHeaders: Boolean = false,
    val listTables: Boolean = false,
    val epubSubdirectory: String = "EPUB",
    val epubMetadata: String? = null,
    epubFonts: List<String> = emptyList(),
    val epubTitlePage: Boolean = true,
    val splitLevel: Long = 1,
    val chunkTemplate: PathTemplate = PathTemplate("%s-%i.html"),
    val tocDepth: Long = 3,
    val referenceDoc: String? = null,
    val referenceLocation: ReferenceLocation = ReferenceLocation.EndOfDocument,
    val figureCaptionPosition: CaptionPosition = CaptionPosition.CaptionBelow,
    val tableCaptionPosition: CaptionPosition = CaptionPosition.CaptionAbove,
    syntaxMap: SyntaxMap = Syntaxes.defaultSyntaxMap,
    val preferAscii: Boolean = false,
    val linkImages: Boolean = false,
 ) : HasSyntaxExtensions {
    val numberOffset: List<Long> = Collections.unmodifiableList(numberOffset.toList())
    val epubFonts: List<String> = Collections.unmodifiableList(epubFonts.toList())
    val syntaxMap: SyntaxMap = snapshotSyntaxMap(syntaxMap)

    /** Source record updates preserve every unspecified field. */
    fun copy(
        template: Template<String>? = this.template,
        variables: Context<String> = this.variables,
        tabStop: Long = this.tabStop,
        tableOfContents: Boolean = this.tableOfContents,
        listOfFigures: Boolean = this.listOfFigures,
        listOfTables: Boolean = this.listOfTables,
        incremental: Boolean = this.incremental,
        mathMethod: MathMethod = this.mathMethod,
        numberSections: Boolean = this.numberSections,
        numberOffset: List<Long> = this.numberOffset,
        sectionDivs: Boolean = this.sectionDivs,
        extensions: Extensions = this.extensions,
        referenceLinks: Boolean = this.referenceLinks,
        dpi: Long = this.dpi,
        wrapText: WrapOption = this.wrapText,
        columns: Long = this.columns,
        emailObfuscation: ObfuscationMethod = this.emailObfuscation,
        identifierPrefix: String = this.identifierPrefix,
        citeMethod: CiteMethod = this.citeMethod,
        htmlQTags: Boolean = this.htmlQTags,
        slideLevel: Long? = this.slideLevel,
        topLevelDivision: TopLevelDivision = this.topLevelDivision,
        highlightMethod: HighlightMethod = this.highlightMethod,
        setextHeaders: Boolean = this.setextHeaders,
        listTables: Boolean = this.listTables,
        epubSubdirectory: String = this.epubSubdirectory,
        epubMetadata: String? = this.epubMetadata,
        epubFonts: List<String> = this.epubFonts,
        epubTitlePage: Boolean = this.epubTitlePage,
        splitLevel: Long = this.splitLevel,
        chunkTemplate: PathTemplate = this.chunkTemplate,
        tocDepth: Long = this.tocDepth,
        referenceDoc: String? = this.referenceDoc,
        referenceLocation: ReferenceLocation = this.referenceLocation,
        figureCaptionPosition: CaptionPosition = this.figureCaptionPosition,
        tableCaptionPosition: CaptionPosition = this.tableCaptionPosition,
        syntaxMap: SyntaxMap = this.syntaxMap,
        preferAscii: Boolean = this.preferAscii,
        linkImages: Boolean = this.linkImages,
    ): WriterOptions = WriterOptions(
        template = template,
        variables = variables,
        tabStop = tabStop,
        tableOfContents = tableOfContents,
        listOfFigures = listOfFigures,
        listOfTables = listOfTables,
        incremental = incremental,
        mathMethod = mathMethod,
        numberSections = numberSections,
        numberOffset = numberOffset,
        sectionDivs = sectionDivs,
        extensions = extensions,
        referenceLinks = referenceLinks,
        dpi = dpi,
        wrapText = wrapText,
        columns = columns,
        emailObfuscation = emailObfuscation,
        identifierPrefix = identifierPrefix,
        citeMethod = citeMethod,
        htmlQTags = htmlQTags,
        slideLevel = slideLevel,
        topLevelDivision = topLevelDivision,
        highlightMethod = highlightMethod,
        setextHeaders = setextHeaders,
        listTables = listTables,
        epubSubdirectory = epubSubdirectory,
        epubMetadata = epubMetadata,
        epubFonts = epubFonts,
        epubTitlePage = epubTitlePage,
        splitLevel = splitLevel,
        chunkTemplate = chunkTemplate,
        tocDepth = tocDepth,
        referenceDoc = referenceDoc,
        referenceLocation = referenceLocation,
        figureCaptionPosition = figureCaptionPosition,
        tableCaptionPosition = tableCaptionPosition,
        syntaxMap = syntaxMap,
        preferAscii = preferAscii,
        linkImages = linkImages,
    )
}
